  static const double s6 = 32;

  static const Map<String, double> all = <String, double>{
    '1': s1,
    '2': s2,
    '3': s3,
    '4': s4,
    '5': s5,
    '6': s6,
  };

  /// Screen margin is 16. DESIGN.md § Layout & Spacing.
  static const double screenMargin = s4;

